/**
 * 环境光晕。两层非常大的浅雾蓝/米白径向光晕,32 秒走完一个来回。
 *
 * ## 它是什么、不是什么
 *
 * 它**不是装饰**:它的用途是让成长空间列表、工作台画布和首页那几块大面积空背景
 * 不至于像一张贴死的纸。规范给它的验收标准是反向的 —— "关掉动画之后才略有察觉"。
 * 如果用户能一眼指出背景在动,那就是幅度错了,不是这里写得不够。
 *
 * 所以它只是一层 `pointer-events:none` 的伪元素:`aria-hidden`、不参与布局、
 * 不接受指针、不改变任何正文的对比度(两层合起来最高 0.055 的不透明度,
 * 而且都落在正文之下的那一层)。所有动画与降级都写在 `motion.css` 里。
 *
 * ## 放在哪
 *
 * - 成长空间列表与首页:放在页面容器里,层本身是 `position:fixed`
 *   (那两个页面自己不滚动,滚动的是父层 `.app-main` —— `absolute` 会跟着滚走);
 * - 工作台:放在 `.path-canvas` 里,层是 `position:absolute`
 *   (画布下面那层 `.workspace` 是不透明的,`fixed` 会被整个盖住)。
 *
 * 定位规则在 `motion.css` 里按父容器区分,这个组件本身不带任何位置。
 */
export function AmbientGlow() {
  return <div className="ambient-glow" aria-hidden="true" />;
}
