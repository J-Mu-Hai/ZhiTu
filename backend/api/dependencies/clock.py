"""此刻几点 —— 一个**可以替换**的依赖。

## 为什么"现在"要走依赖注入

提醒里有一条判据是**钟点**,不是数据:免打扰时段(默认 22:00–08:00)会把
"你该去做事了"那类提醒压住,只留下"有事情在等你"那类(见
`services/reminder_service.py` 的 `_STATE_KINDS`)。

于是"读提醒"这件事的结果**取决于跑它的那一刻**。一条测试如果拿真实时钟当输入,
那它就不是在验规则,而是在验"我们碰巧在哪个钟点跑的它":

- 22:00–08:00 之间跑,安静的用例必红;
- 换个钟点跑,压制的用例必红。

两边都是**确定的**,只是判据挂在墙上。要验规则,就得能**指定**那一刻。

和 `get_reasoner` 同一个做法(见 `dependencies/agent.py`):测试用
`app.dependency_overrides[get_now]` 换掉它。生产路径上没有任何分支 —— 换与不换,
`reminder_service` 走的都是同一条规矩,规则本身没有为测试让路。

## 为什么返回带时区的 UTC

"此刻"是一个绝对时刻,不该带某个地方的口径。用户所在时区是**用户自己的属性**
(`user.timezone`),由服务层拿去换算。这里要是返回一个本地朴素时间,服务层就必须
猜它是什么时区 —— 而猜错的表现是免打扰窗口整体偏移几小时,没有人会看出来。
"""

from __future__ import annotations

from datetime import UTC, datetime


def get_now() -> datetime:
    """此刻,带 UTC 时区。

    `UTC` 而不是裸 `datetime.now()`:裸的是**服务器本地**时间,且没有时区,服务层再拿它
    去 `astimezone` 会按服务器时区解释 —— 部署在 UTC 的机器上和本机得到的结果不一样,
    而这条路径上没有任何东西会报错。
    """
    return datetime.now(UTC)
